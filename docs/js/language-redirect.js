(() => {
  "use strict";

  const LANGUAGES = new Set(["en", "zh", "zh-trad"]);
  const DEFAULT_LANGUAGE = "en";
  const REDIRECTABLE_EXTENSIONS = new Set([
    "html",
    "htm",
    "xml",
    "json",
    "md",
    "txt",
  ]);

  const preferences = () => {
    if (typeof navigator === "undefined") return [];
    const values = navigator.languages || (navigator.language ? [navigator.language] : []);
    return values
      .map((value) => String(value).trim().toLowerCase())
      .filter(Boolean);
  };

  const chooseLanguage = () => {
    for (const preference of preferences()) {
      const tag = preference.split(";", 1)[0].trim();
      const subtags = tag.split("-").slice(1);
      if (tag === "en" || tag.split("-")[0] === "en") return "en";
      if (tag.split("-")[0] !== "zh") continue;
      if (subtags.some((subtag) => ["hant", "tw", "hk", "mo"].includes(subtag))) {
        return "zh-trad";
      }
      return "zh";
    }
    return DEFAULT_LANGUAGE;
  };

  const languagePrefix = () => {
    const first = window.location.pathname.split("/")[1];
    return LANGUAGES.has(first) ? first : null;
  };

  window.tdLanguageRedirect = (targetHref) => {
    const target = new URL(targetHref, window.location.href);
    // The root alias generated by defaultContentLanguageInSubdir points at the
    // English home.  It is the only alias where we replace the fixed English
    // target with the browser's preferred language.
    if (/^\/(?:en|zh|zh-trad)\/?$/.test(target.pathname)) {
      window.location.replace(`/${chooseLanguage()}/`);
      return;
    }
    window.location.replace(target.href);
  };

  window.tdHandleMissingPage = () => {
    const currentPrefix = languagePrefix();
    if (currentPrefix) {
      // GitHub Pages serves the root 404 for missing URLs in every directory.
      // Hand language-scoped misses to the normal Hugo 404 for that language.
      window.location.replace(`/${currentPrefix}/404.html`);
      return;
    }

    const path = window.location.pathname;
    const lastSegment = path.split("/").filter(Boolean).pop() || "";
    const extensionMatch = lastSegment.match(/\.([a-z0-9]+)$/i);
    const extension = extensionMatch ? extensionMatch[1].toLowerCase() : null;
    const redirectable = !extension || REDIRECTABLE_EXTENSIONS.has(extension);
    if (!redirectable) return;

    let suffix = path;
    if (/\/index\.html?$/i.test(path)) {
      suffix = path.replace(/index\.html?$/i, "");
    } else if (!extension && !path.endsWith("/")) {
      suffix = `${path}/`;
    }
    const target = `/${chooseLanguage()}${suffix}${window.location.search}${window.location.hash}`;
    window.location.replace(target);
  };
})();
